// @ts-check
import { existsSync } from 'node:fs';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { satteri } from '@astrojs/markdown-satteri';
import { engines, systems } from './src/lib/registry.mjs';
import { wikiMarkdown } from './src/lib/markdown.mjs';

// GitHub Pages serves a project site under /<repository>/; CI sets these. Locally the site is at /.
const site = process.env.WIKI_SITE || 'http://localhost:4321';
const base = process.env.WIKI_BASE || '/';

// Each engine: its overview, then its systems in the registry's reading order, named from the registry (an
// autogenerated group would be labelled with the bare folder name).
const engineGroups = engines
  .filter((e) => existsSync(`src/content/docs/engines/${e.id}`))
  .map((e) => ({
    label: e.name,
    collapsed: true,
    items: [
      { label: 'Overview', link: `/engines/${e.id}/` },
      ...systems
        .filter((s) => existsSync(`src/content/docs/engines/${e.id}/${s.id}`))
        .map((s) => ({ label: s.name, collapsed: true, items: [{ autogenerate: { directory: `engines/${e.id}/${s.id}` } }] })),
    ],
  }));

const group = (label, directory, collapsed = false) =>
  existsSync(`src/content/docs/${directory}`) ? [{ label, collapsed, items: [{ autogenerate: { directory } }] }] : [];

export default defineConfig({
  site,
  base,
  trailingSlash: 'always',
  markdown: {
    processor: satteri({ mdastPlugins: [wikiMarkdown({ base })] }),
  },
  integrations: [
    starlight({
      title: 'Engine Wiki',
      description: 'How games store and process their data: engines, formats and what is known for sure.',
      customCss: ['./src/styles/wiki.css'],
      components: {
        MarkdownContent: './src/components/MarkdownContent.astro',
      },
      lastUpdated: true,
      sidebar: [
        { label: 'Start here', items: [{ autogenerate: { directory: 'guide' } }] },
        { label: 'Coverage', link: '/coverage/' },
        ...(engineGroups.length ? [{ label: 'Engines', items: engineGroups }] : []),
        ...group('Games', 'games', true),
        ...group('Concepts', 'concepts', true),
        ...group('Methods', 'methods', true),
      ],
    }),
  ],
});
